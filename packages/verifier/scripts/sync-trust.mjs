#!/usr/bin/env node
// Regenerates src/v3/trust/*.ts from a tinfoil-go checkout, so the embedded
// trust anchors stay byte-identical across SDKs.
//
//   node scripts/sync-trust.mjs <path-to-tinfoil-go>
//
// Each module exports one string constant. Sources are read from the
// checkout's HEAD commit, not its working tree, and that revision is recorded
// in src/v3/trust/SOURCE so CI can diff against a pinned checkout.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const goRepo = process.argv[2];
if (!goRepo) {
  console.error("usage: sync-trust.mjs <path-to-tinfoil-go>");
  process.exit(2);
}
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "v3", "trust");

const files = [
  {
    name: "sigstore-trusted-root.ts",
    constant: "SIGSTORE_TRUSTED_ROOT_JSON",
    doc: "The Sigstore public-good trusted root (TUF trusted_root.json) all provenance bundles verify against.",
    source: "verify/internal/endorsement/trusted_root.json",
  },
  {
    name: "amd-genoa-chain.ts",
    constant: "AMD_GENOA_CERT_CHAIN_PEM",
    doc: "AMD KDS certificate chain for Genoa: the ASK followed by the self-signed ARK.",
    source: "verify/internal/quote/sev/genoa_cert_chain.pem",
  },
  {
    name: "amd-turin-chain.ts",
    constant: "AMD_TURIN_CERT_CHAIN_PEM",
    doc: "AMD KDS certificate chain for Turin: the ASK followed by the self-signed ARK.",
    source: "verify/internal/quote/sev/turin_cert_chain.pem",
  },
  {
    name: "intel-sgx-root.ts",
    constant: "INTEL_SGX_ROOT_CA_PEM",
    doc: "The Intel SGX Root CA that anchors every TDX PCK certificate chain.",
    source: "verify/internal/quote/tdx/sgx_root_ca.pem",
  },
];

const rev = execFileSync("git", ["-C", goRepo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const atHead = (path) => execFileSync("git", ["-C", goRepo, "show", `HEAD:${path}`], { encoding: "utf8" });
const header = `// Generated by scripts/sync-trust.mjs from tinfoil-go ${rev}. Do not edit.\n\n`;

for (const f of files) {
  const text = atHead(f.source);
  writeFileSync(join(out, f.name), `${header}/** ${f.doc} */\nexport const ${f.constant} = ${JSON.stringify(text)};\n`);
}

// The signing key is an inline constant in Go, not a file.
const keysGo = atHead("verify/internal/endorsement/signing_keys.go");
const pem = /-----BEGIN PUBLIC KEY-----[\s\S]*?-----END PUBLIC KEY-----/.exec(keysGo)?.[0];
if (!pem) throw new Error("signing key PEM not found in signing_keys.go");
writeFileSync(
  join(out, "signing-keys.ts"),
  `${header}/** Tinfoil's ECDSA P-256 public key that signs config endorsements and artifact-freshness approvals. */\nexport const PUBLIC_SIGNING_KEY_PEM = ${JSON.stringify(pem)};\n`,
);
writeFileSync(join(out, "SOURCE"), `tinfoil-go ${rev}\n`);
console.log(`trust material synced from tinfoil-go ${rev}`);
