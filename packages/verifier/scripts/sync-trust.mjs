#!/usr/bin/env node
// Refreshes the embedded trust anchors in src/v3/trust/ from their publishers:
//
//   - the Sigstore trusted root, through the Sigstore TUF repository, so the
//     target is authenticated by the TUF root of trust;
//   - the AMD SEV-SNP certificate chains (ASK then ARK) for each supported
//     product line, from the AMD Key Distribution Service;
//   - the Intel SGX Root CA, from Intel's certificate service.
//
// Tinfoil's signing key in src/v3/trust/signing-keys.ts is maintained by
// hand, not fetched.
//
//   npm run sync:trust
//
// Each module exports one string constant. src/v3/trust/SOURCE records where
// each file came from, when, and its SHA-256.
import { TrustedRootProvider } from "@freedomofpress/sigstore-browser";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "v3", "trust");

const AMD_KDS = "https://kdsintf.amd.com/vcek/v1";
const INTEL_SGX_ROOT = "https://certificates.trustedservices.intel.com/Intel_SGX_Provisioning_Certification_RootCA.pem";

async function fetchPem(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  // Publishers differ in line endings; the content is the same certificates.
  const text = (await res.text()).replace(/\r\n/g, "\n");
  if (!text.startsWith("-----BEGIN CERTIFICATE-----")) throw new Error(`${url}: not a PEM certificate`);
  return text.endsWith("\n") ? text : text + "\n";
}

async function fetchSigstoreRoot() {
  const provider = new TrustedRootProvider({ disableCache: true });
  const root = await provider.getTrustedRoot();
  return JSON.stringify(root, null, 2) + "\n";
}

const files = [
  {
    name: "sigstore-trusted-root.ts",
    constant: "SIGSTORE_TRUSTED_ROOT_JSON",
    doc: "The Sigstore public-good trusted root all provenance bundles verify against.",
    source: "Sigstore TUF repository (trusted_root.json target)",
    fetch: fetchSigstoreRoot,
  },
  {
    name: "amd-genoa-chain.ts",
    constant: "AMD_GENOA_CERT_CHAIN_PEM",
    doc: "AMD KDS certificate chain for Genoa: the ASK followed by the self-signed ARK.",
    source: `${AMD_KDS}/Genoa/cert_chain`,
    fetch: () => fetchPem(`${AMD_KDS}/Genoa/cert_chain`),
  },
  {
    name: "amd-turin-chain.ts",
    constant: "AMD_TURIN_CERT_CHAIN_PEM",
    doc: "AMD KDS certificate chain for Turin: the ASK followed by the self-signed ARK.",
    source: `${AMD_KDS}/Turin/cert_chain`,
    fetch: () => fetchPem(`${AMD_KDS}/Turin/cert_chain`),
  },
  {
    name: "intel-sgx-root.ts",
    constant: "INTEL_SGX_ROOT_CA_PEM",
    doc: "The Intel SGX Root CA that anchors every TDX PCK certificate chain.",
    source: INTEL_SGX_ROOT,
    fetch: () => fetchPem(INTEL_SGX_ROOT),
  },
];

const fetchedAt = new Date().toISOString();
const record = [`fetched ${fetchedAt} by scripts/sync-trust.mjs`, ""];
for (const f of files) {
  const text = await f.fetch();
  const sha256 = createHash("sha256").update(text).digest("hex");
  writeFileSync(
    join(out, f.name),
    `// Generated by scripts/sync-trust.mjs. Do not edit; run \`npm run sync:trust\`.\n\n/** ${f.doc} */\nexport const ${f.constant} = ${JSON.stringify(text)};\n`,
  );
  record.push(`${f.name}`, `  source: ${f.source}`, `  sha256: ${sha256}`);
  console.log(`${f.name}: ${sha256.slice(0, 16)}… from ${f.source}`);
}
writeFileSync(join(out, "SOURCE"), record.join("\n") + "\n");
